/****************************************************************************
 * board/contest_board/scripts/bk7258_boot_head.c
 *
 * BK7258 启动头信息
 *
 * BK7258 的 Bootloader 在加载 kernel 时, 需要读取头部信息确定:
 *   - 镜像加载地址
 *   - 镜像入口地址
 *   - 镜像大小
 *   - 校验和
 *
 * 本文件定义头部结构, 在链接时放置在 kernel 镜像起始位置。
 *
 ****************************************************************************/

#ifndef __BK7258_BOOT_HEAD_H
#define __BK7258_BOOT_HEAD_H

#include <stdint.h>

/****************************************************************************
 * 镜像魔数
 ****************************************************************************/

#define BK7258_IMAGE_MAGIC       0x424B3738   /* "BK78" ASCII */
#define BK7258_IMAGE_VERSION     1

/****************************************************************************
 * 镜像类型
 ****************************************************************************/

#define BK7258_IMAGE_TYPE_BOOT   0x01          /* Bootloader */
#define BK7258_IMAGE_TYPE_KERNEL 0x02          /* Kernel */
#define BK7258_IMAGE_TYPE_APP    0x03          /* Application */
#define BK7258_IMAGE_TYPE_MODEL  0x04          /* AI Model */
#define BK7258_IMAGE_TYPE_FS     0x05          /* Filesystem */

/****************************************************************************
 * 镜像头结构 (64 字节)
 ****************************************************************************/

struct bk7258_image_header_s
{
  uint32_t magic;            /* 魔数: 0x424B3738 */
  uint32_t version;          /* 头版本 */
  uint32_t type;             /* 镜像类型 */
  uint32_t loadAddr;         /* 加载地址 */
  uint32_t entryAddr;        /* 入口地址 */
  uint32_t imageSize;        /* 镜像大小 (不含头) */
  uint32_t checksum;         /* 校验和 (CRC32) */
  uint32_t reserved[8];      /* 保留字段 */
  uint32_t headerCrc;        /* 头部 CRC32 */
};

/****************************************************************************
 * 镜像头尺寸
 ****************************************************************************/

#define BK7258_IMAGE_HEADER_SIZE  sizeof(struct bk7258_image_header_s)

/****************************************************************************
 * 编译时断言: 头部必须 64 字节
 ****************************************************************************/

#define BK7258_HEADER_ASSERT \
  typedef char header_size_check[(BK7258_IMAGE_HEADER_SIZE == 64) ? 1 : -1]

#endif /* __BK7258_BOOT_HEAD_H */
